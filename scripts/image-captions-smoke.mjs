import { chromium, expect } from "@playwright/test";
import sharp from "sharp";
import assert from "node:assert/strict";
const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 940, height: 650 } });
  const errors = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(process.env.MOYU_TEST_URL || "http://127.0.0.1:1420");
  await page.getByRole("tab", { name: "提醒", exact: true }).click();
  await page.getByRole("checkbox", { name: "弹窗", exact: true }).check();
  const files = await Promise.all(["one", "two"].map(async (name, i) => ({ name: `${name}.png`, mimeType: "image/png", buffer: await sharp({ create: { width: 360, height: 250, channels: 4, background: i ? "#267c62" : "#ed6370" } }).png().toBuffer() })));
  await page.getByLabel("选择提醒图片").setInputFiles(files);
  await expect(page.locator(".gallery-list li")).toHaveCount(2);
  await page.getByLabel("one.png 标题", { exact: true }).fill("First title");
  await page.getByLabel("one.png 文案", { exact: true }).fill("First caption");
  await expect(page.locator(".preview-window .ad-caption")).toContainText("First caption");
  await page.getByLabel("two.png 标题", { exact: true }).fill("Second title");
  await page.getByLabel("two.png 文案", { exact: true }).fill("Second caption");
  await page.getByLabel("two.png 文案", { exact: true }).pressSequentially(" with rapid edits", { delay: 45 });
  await page.getByLabel("two.png 文案", { exact: true }).blur();
  await page.getByRole("button", { name: "预览 one.png", exact: true }).click();
  await expect(page.locator(".preview-window .ad-caption")).toContainText("First caption");
  await page.waitForTimeout(800);
  await page.reload();
  await page.getByRole("tab", { name: "提醒", exact: true }).click();
  await expect(page.getByLabel("one.png 文案", { exact: true })).toHaveValue("First caption");
  await expect(page.getByLabel("two.png 文案", { exact: true })).toHaveValue("Second caption with rapid edits");
  await page.getByLabel("图片抽取方式").selectOption("sequential");
  await page.getByRole("button", { name: /测试提醒/ }).click();
  await expect(page.locator(".browser-popup .ad-caption")).toContainText("First caption");
  await page.waitForTimeout(3200);
  await page.getByRole("button", { name: /测试提醒/ }).click();
  await expect(page.locator(".browser-popup .ad-caption")).toContainText("Second caption with rapid edits");
  await page.waitForTimeout(3200);
  await page.getByLabel("two.png 标题", { exact: true }).fill("   ");
  await page.getByLabel("two.png 文案", { exact: true }).fill("");
  await page.getByLabel("two.png 文案", { exact: true }).blur();
  await expect(page.locator(".preview-window .ad-caption")).toHaveCount(0);
  await expect(page.locator(".preview-window img")).toBeVisible();
  await page.screenshot({ path: "test-results/image-caption-editor.png" });
  assert.deepEqual(errors, []);
  console.log("PASS: per-image inline captions, live preview selection, rapid edit persistence, image/caption pairing during sequential alerts, and blank overlay removal.");
} finally { await browser.close(); }
