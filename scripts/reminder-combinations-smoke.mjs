import { chromium, expect } from "@playwright/test";
import assert from "node:assert/strict";
import sharp from "sharp";

const browser = await chromium.launch({ channel: "msedge", headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 940, height: 650 } });
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(process.env.MOYU_TEST_URL || "http://127.0.0.1:1420");
  await page.getByRole("tab", { name: "提醒", exact: true }).click();
  await page.getByRole("checkbox", { name: "弹窗", exact: true }).check();
  await expect(page.getByRole("checkbox", { name: "边缘光", exact: true })).toBeChecked();
  await expect(page.locator(".preview-native-surface .glow-layer.active")).toHaveCount(1);
  await expect(page.locator(".preview-native-surface .popup-card img")).toBeVisible();
  await expect(page.getByRole("checkbox", { name: "自动操作", exact: true })).not.toBeChecked();
  await page.getByRole("slider", { name: "边缘光离开后保留", exact: true }).fill("2");
  await page.getByRole("slider", { name: "弹窗离开后保留", exact: true }).fill("8");
  await page.getByLabel("默认耳机广告 标题", { exact: true }).fill("会议提醒");
  await page.getByLabel("默认耳机广告 文案", { exact: true }).fill("请查看入口\n准备切换到工作窗口");
  await page.getByLabel("弹窗宽度", { exact: true }).fill("480");
  await page.getByLabel("弹窗宽度", { exact: true }).blur();
  await page.getByLabel("弹窗高度", { exact: true }).fill("320");
  await page.getByLabel("弹窗高度", { exact: true }).blur();
  await page.getByLabel("弹窗位置", { exact: true }).selectOption("top-left");
  await page.getByRole("slider", { name: "弹窗不透明度", exact: true }).fill("0.65");
  await page.getByLabel("提醒颜色", { exact: true }).fill("#00e060");
  await page.getByRole("button", { name: /测试提醒/ }).click();
  await expect(page.locator(".app-shell > .glow-layer.active")).toHaveCount(1);
  await expect(page.locator(".browser-popup .popup-card img")).toBeVisible();
  await expect(page.locator(".browser-popup .ad-caption")).toContainText("会议提醒");
  await page.mouse.move(900, 600);
  await expect(page.locator(".browser-popup .popup-close")).toHaveCSS("background-color", "rgba(255, 255, 255, 0)");
  assert.equal(await page.locator(".browser-popup .popup-content").evaluate((el) => getComputedStyle(el).opacity), "0.65");
  const popup = await page.locator(".browser-popup").boundingBox();
  assert.deepEqual(popup, { x: 12, y: 12, width: 480, height: 320 });
  await page.getByRole("button", { name: "关闭并暂停提醒", exact: true }).click();
  await expect(page.locator(".browser-popup")).toHaveCount(0);
  await expect(page.locator(".app-shell > .glow-layer.active")).toHaveCount(0);
  await page.getByRole("button", { name: "恢复提醒", exact: true }).click();
  await page.waitForTimeout(500);
  await page.reload();
  await page.getByRole("tab", { name: "提醒", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: "边缘光", exact: true })).toBeChecked();
  await expect(page.getByRole("checkbox", { name: "弹窗", exact: true })).toBeChecked();
  await expect(page.getByLabel("弹窗宽度", { exact: true })).toHaveValue("480");
  await expect(page.getByLabel("默认耳机广告 标题", { exact: true })).toHaveValue("会议提醒");
  await expect(page.getByRole("slider", { name: "边缘光离开后保留", exact: true })).toHaveValue("2");
  await expect(page.getByRole("slider", { name: "弹窗离开后保留", exact: true })).toHaveValue("8");
  for (const viewport of [{ width: 940, height: 650 }, { width: 700, height: 500 }, { width: 1440, height: 900 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport);
    await page.locator(".reminder-editor").evaluate((el) => { el.scrollTop = 0; });
    await page.waitForTimeout(450);
    assert(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth && document.documentElement.scrollHeight === innerHeight), "Combined settings must stay within viewport");
    await expect(page.getByRole("button", { name: /测试提醒/ })).toBeInViewport();
    if (viewport.width > 620) {
      const preview = await page.locator(".reminder-media").boundingBox();
      const editor = await page.locator(".reminder-editor").boundingBox();
      assert(preview.x + preview.width < editor.x, "Preview must be left of the editor");
      assert(viewport.width - editor.x - editor.width <= 21, "Editor must reach the window's right padding");
    }
    const pixels = await sharp(await page.locator(".preview-window").screenshot()).removeAlpha().raw().toBuffer();
    let green = 0;
    for (let i = 0; i < pixels.length; i += 3) if (pixels[i + 1] > pixels[i] + 25 && pixels[i + 1] > pixels[i + 2] + 25) green++;
    assert(green > 20, "Combined preview renders colored edges");
    await page.screenshot({ path: `test-results/reminder-combined-${viewport.width}.png` });
  }
  await page.getByLabel("默认耳机广告 标题", { exact: true }).fill("");
  await page.getByLabel("默认耳机广告 文案", { exact: true }).fill("");
  await expect(page.locator(".preview-window .ad-caption")).toHaveCount(0);
  await expect(page.locator(".preview-window img")).toBeVisible();
  await page.getByRole("checkbox", { name: "自动操作", exact: true }).check();
  await page.getByRole("checkbox", { name: "打开网页", exact: true }).check();
  await page.getByLabel("网页地址", { exact: true }).fill("javascript:alert(1)");
  await expect(page.getByLabel("网页地址", { exact: true })).toHaveAttribute("aria-invalid", "true");
  await expect(page.getByRole("button", { name: "测试自动操作", exact: true })).toBeDisabled();
  await page.getByLabel("网页地址", { exact: true }).fill("https://example.com/");
  await expect(page.getByLabel("网页地址", { exact: true })).toHaveAttribute("aria-invalid", "false");
  await page.getByRole("checkbox", { name: "自动操作", exact: true }).uncheck();
  await expect(page.getByLabel("网页地址", { exact: true })).toHaveCount(0);
  await page.getByRole("checkbox", { name: "自动操作", exact: true }).check();
  await expect(page.getByLabel("网页地址", { exact: true })).toHaveValue("https://example.com/");
  await page.getByRole("slider", { name: "屏幕边距", exact: true }).fill("200");
  await page.getByRole("button", { name: /测试提醒/ }).click();
  const compact = await page.locator(".browser-popup").boundingBox();
  assert.ok(compact.width >= 180 && compact.height >= 120 && compact.x >= 0 && compact.x + compact.width <= 390, "Large margins must preserve a usable popup");
  await expect(page.getByRole("button", { name: "关闭并暂停提醒", exact: true })).toBeInViewport();
  await page.getByRole("button", { name: "关闭并暂停提醒", exact: true }).click();
  assert.deepEqual(errors, []);
  console.log("PASS: image captions, blank caption removal, transparent close button, independent durations, automation toggle, left preview/right editor, custom popup, snooze, and responsive layout.");
} finally { await browser.close(); }
